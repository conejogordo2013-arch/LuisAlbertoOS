%ifndef LA_GUI_TEXT_ASM
%define LA_GUI_TEXT_ASM

gui_draw_text:
    ; EAX=x EBX=y ESI=ptr zero-term string EDI=color
    pushad
.n:
    mov dl, [esi]
    test dl, dl
    jz .o
    cmp dl, 'a'
    jb .u
    cmp dl, 'z'
    ja .u
    sub dl, 32
.u:
    mov ecx, eax
    movzx edx, dl
    call gui_draw_glyph_bios
    add eax, 8
    inc esi
    jmp .n
.o:
    popad
    ret

gui_draw_glyph_bios:
    ; ECX=x EBX=y EDX=char EDI=color (compatibilidad BIOS)
    ; Reutiliza la fuente del sistema para mantener legibilidad en modo gráfico.
    call gui_draw_glyph
    ret

gui_draw_glyph:
    ; ECX=x EBX=y EDX=char EDI=color
    pushad
    cmp edx, 'A'
    jb .digit
    cmp edx, 'Z'
    ja .digit
    sub edx, 'A'
    imul edx, edx, 5
    mov esi, gui_font_letters
    add esi, edx
    jmp .draw
.digit:
    cmp edx, '0'
    jb .special
    cmp edx, '9'
    ja .special
    sub edx, '0'
    imul edx, edx, 5
    mov esi, gui_font_digits
    add esi, edx
    jmp .draw
.special:
    cmp edx, ':'
    jne .dash
    mov esi, gui_font_colon
    jmp .draw
.dash:
    cmp edx, '-'
    jne .dot
    mov esi, gui_font_dash
    jmp .draw
.dot:
    cmp edx, '.'
    jne .space
    mov esi, gui_font_dot
    jmp .draw
.space:
    popad
    ret
.draw:
    xor edx, edx
.col:
    cmp edx, 5
    jae .out
    mov al, [esi+edx]
    xor ebp, ebp
.row:
    cmp ebp, 7
    jae .next
    bt eax, ebp
    jnc .skip
    mov eax, ecx
    add eax, edx
    mov ebx, [esp+16]
    add ebx, ebp
    mov esi, edi
    call graphics_draw_pixel
.skip:
    inc ebp
    jmp .row
.next:
    inc edx
    jmp .col
.out:
    popad
    ret

